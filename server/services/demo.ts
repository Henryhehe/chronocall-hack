import type { AiServices } from "./types.ts";
import type { LowPolyObjectBlueprint } from "../../src/types/world3d.ts";

function demoObject(name: string, x: number, z: number): LowPolyObjectBlueprint {
  return {
    id: `demo-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    name, kind: "crystal", description: "Local demo fixture; not generated by Gemini.",
    x, z, rotationY: 0, scale: 1, interactionEffect: "pulse",
    parts: [{ shape: "octahedron", color: "#22D3EE", emissive: "#0891B2", emissiveIntensity: 0.5,
      roughness: 0.4, metalness: 0.2, position: [0, 1, 0], rotation: [0, 0, 0], size: [1, 1.5, 1] }],
  };
}

/** Explicit fixtures. Requests reach this server but are never sent to Gemini. */
export const demoServices: AiServices = {
  async detectObjectsInFrame() {
    return { summary: "Demo mode: camera capture works; object detection requires a Gemini API key.", objects: [], latencyMs: 0, model: "demo" };
  },
  async askAboutFrame() {
    return { answer: "Demo mode: this is a local placeholder. Start without DEMO_MODE to ask Gemini about the frame.", latencyMs: 0, model: "demo" };
  },
  async transformSelfieToCharacterWorld({ imageBase64, mimeType }) {
    return { imageDataUrl: `data:${mimeType};base64,${imageBase64}`, mimeType, note: "Demo mode: original photo retained; no AI transformation was performed.", latencyMs: 0, model: "demo" };
  },
  async interactWithWorldObject({ objectName }) {
    return { reply: `Demo: you activate ${objectName}.`, worldEffect: "shimmer", latencyMs: 0 };
  },
  async generateLowPolyScene() {
    return {
      sceneName: "Demo Crystal Courtyard", atmosphereDescription: "A fixed local fixture for UI development.",
      palette: { skyColor: "#141E30", fogColor: "#141E30", groundColor: "#5B6470", groutColor: "#28303D", accentColor: "#06B6D4", sunColor: "#FFE8C8", sunIntensity: 2.1, hemiSky: "#93C5FD", hemiGround: "#334155", rain: false },
      objects: [demoObject("West Crystal", -5, -4), demoObject("East Crystal", 5, -4), demoObject("Central Crystal", 0, -8)],
      latencyMs: 0, model: "demo",
    };
  },
  async spawnLowPolyObject({ objectPrompt, x, z }) {
    return { object: demoObject(objectPrompt.trim().slice(0, 40) || "Demo Crystal", x, z), latencyMs: 0, model: "demo" };
  },
  async createGenieSession() {
    throw new Error("Genie streaming is unavailable in demo mode. Configure GEMINI_API_KEY and restart without DEMO_MODE.");
  },
};
